// Writes supabase/seed.sql from public/data/<area>/ so the database matches the map.
//   node scripts/make-seed.mjs        (run after `npm run data` or after editing drains.json)

import { readFile, writeFile } from "node:fs/promises";

const AREA = "bukit-raja";
const dataDir = new URL(`../public/data/${AREA}/`, import.meta.url);
const drains = JSON.parse(await readFile(new URL("drains.json", dataDir), "utf8"));
const streets = JSON.parse(await readFile(new URL("streets.geojson", dataDir), "utf8"));

const q = (v) => (v === null || v === undefined ? "null" : typeof v === "number" ? String(v) : `'${String(v).replaceAll("'", "''")}'`);
const rows = (list) => list.map((r) => `  (${r.map(q).join(", ")})`).join(",\n");

const sql = `-- Generated by scripts/make-seed.mjs from public/data/${AREA}/ — do not edit by hand.

insert into public.drains (id, name, lng, lat, elevation_m, bank_cm, catchment_factor, outflow_cm_per_min) values
${rows(drains.map((d) => [d.id, d.name, d.lng, d.lat, d.elevation_m, d.bank_cm, d.catchment_factor, d.outflow_cm_per_min]))};

insert into public.streets (id, name, highway, drain_id) values
${rows(streets.features.map(({ properties: p }) => [p.id, p.name, p.highway, p.drain_id]))};

insert into public.drain_status (drain_id) values
${rows(drains.map((d) => [d.id]))};
`;

await writeFile(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`seed.sql: ${drains.length} drains, ${streets.features.length} streets`);
