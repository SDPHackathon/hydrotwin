// Voice-over: ElevenLabs' official text-to-speech API, one call per line of lines.json.
// Each line → public/voice/<id>.mp3 + scripts/voice/out/<id>.json (duration + word timings),
// then src/v3/voice.ts is regenerated: real timings where a line is voiced, estimates otherwise
// (so the scenes can be built before the voice exists). The API key is read from
// ~/.config/elevenlabs/api-key — outside the repo, never committed.
//   node scripts/voice/tts.mjs voices                    premade voices (name, id, accent)
//   node scripts/voice/tts.mjs credits                   characters used / left this month
//   node scripts/voice/tts.mjs audition v01 <voiceId>…   one line in several voices → public/voice/audition/
//   node scripts/voice/tts.mjs all <voiceId> [v03 …]     every line (or just the ids given)
//   node scripts/voice/tts.mjs index                     only regenerate src/v3/voice.ts
// A line can carry "say" — what the voice reads when it differs from the subtitle "text"
// (e.g. a Malay name respelled so it is pronounced right).
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { homedir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = join(here, "../..");
const AUDIO = join(ROOT, "public/voice");
const OUTDIR = join(here, "out");
const MODEL = "eleven_multilingual_v2";
const SETTINGS = { stability: 0.5, similarity_boost: 0.75, style: 0.2, use_speaker_boost: true, speed: 1.05 };
const WORDS_PER_SECOND = 2.6; // estimate until a line is voiced
const lines = JSON.parse(readFileSync(join(here, "lines.json"), "utf8"));

async function api(path, init = {}) {
  const key = readFileSync(join(homedir(), ".config/elevenlabs/api-key"), "utf8").trim();
  const res = await fetch("https://api.elevenlabs.io" + path, {
    ...init,
    headers: { "xi-api-key": key, "content-type": "application/json" },
  });
  if (!res.ok) throw new Error(`${path} → ${res.status} ${await res.text()}`);
  return res.json();
}

// Character timings → words. Display words come from "text"; if "say" respelled a word,
// the counts still match, so each display word takes the timing of the spoken one.
function wordTimings(alignment, display) {
  const { characters: ch, character_start_times_seconds: s, character_end_times_seconds: e } = alignment;
  const spoken = [];
  let cur = null;
  for (let i = 0; i < ch.length; i++) {
    if (/\s/.test(ch[i])) { cur = null; continue; }
    if (!cur) spoken.push((cur = { word: "", start: s[i], end: e[i] }));
    cur.word += ch[i];
    cur.end = e[i];
  }
  const shown = display.split(/\s+/).filter(Boolean);
  if (shown.length === spoken.length) spoken.forEach((w, i) => (w.word = shown[i]));
  return spoken.map((w) => ({ ...w, start: +w.start.toFixed(3), end: +w.end.toFixed(3) }));
}

function estimate(line) {
  const words = line.text.split(/\s+/).filter(Boolean);
  let t = 0;
  const timed = words.map((word) => {
    const len = (0.6 + word.length / 7) / WORDS_PER_SECOND;
    const w = { word, start: +t.toFixed(3), end: +(t + len * 0.85).toFixed(3) };
    t += len + (/[.,:;!?]$/.test(word) ? 0.25 : 0);
    return w;
  });
  return { id: line.id, duration: +t.toFixed(3), words: timed, estimated: true };
}

function writeIndex() {
  const out = {};
  for (const line of lines) {
    const f = join(OUTDIR, `${line.id}.json`);
    out[line.id] = existsSync(f) ? { ...JSON.parse(readFileSync(f, "utf8")), estimated: false } : estimate(line);
  }
  writeFileSync(
    join(ROOT, "src/v3/voice.ts"),
    `// Generated by scripts/voice/tts.mjs — do not edit by hand.\n` +
      `// Word timings of each voice-over line (seconds); "estimated" until the line is voiced.\n` +
      `export type Word = { word: string; start: number; end: number };\n` +
      `export type Line = { id: string; voice?: string; duration: number; words: Word[]; estimated: boolean };\n` +
      `export const VOICE: Record<string, Line> = ${JSON.stringify(out, null, 1)};\n`,
  );
  console.log(`voice.ts: ${Object.values(out).filter((l) => !l.estimated).length}/${lines.length} lines voiced`);
}

async function speak(line, voiceId, i) {
  const body = { text: line.say ?? line.text, model_id: MODEL, voice_settings: SETTINGS };
  // Neighbouring lines keep the delivery continuous across scenes.
  if (i > 0) body.previous_text = lines[i - 1].say ?? lines[i - 1].text;
  if (i < lines.length - 1) body.next_text = lines[i + 1].say ?? lines[i + 1].text;
  const r = await api(`/v1/text-to-speech/${voiceId}/with-timestamps?output_format=mp3_44100_128`, {
    method: "POST",
    body: JSON.stringify(body),
  });
  const a = r.alignment;
  return {
    mp3: Buffer.from(r.audio_base64, "base64"),
    timing: { id: line.id, voice: voiceId, duration: +a.character_end_times_seconds.at(-1).toFixed(3), words: wordTimings(a, line.text) },
  };
}

const [cmd, ...args] = process.argv.slice(2);
if (cmd === "voices") {
  const { voices } = await api("/v1/voices");
  for (const v of voices.filter((v) => v.category === "premade"))
    console.log([v.name, v.voice_id, v.labels?.gender, v.labels?.accent, v.labels?.age, v.labels?.description ?? v.labels?.descriptive, v.labels?.use_case].filter(Boolean).join(" | "));
} else if (cmd === "credits") {
  const s = await api("/v1/user/subscription");
  console.log(`${s.tier}: ${s.character_count} / ${s.character_limit} characters used`);
} else if (cmd === "audition") {
  const [id, ...voiceIds] = args;
  const i = lines.findIndex((l) => l.id === id);
  mkdirSync(join(AUDIO, "audition"), { recursive: true });
  for (const v of voiceIds) {
    const { mp3, timing } = await speak(lines[i], v, i);
    writeFileSync(join(AUDIO, "audition", `${id}-${v}.mp3`), mp3);
    console.log(`${id}-${v}.mp3 — ${timing.duration} s`);
  }
} else if (cmd === "all") {
  const [voiceId, ...only] = args;
  mkdirSync(AUDIO, { recursive: true });
  mkdirSync(OUTDIR, { recursive: true });
  for (const [i, line] of lines.entries()) {
    if (only.length && !only.includes(line.id)) continue;
    const { mp3, timing } = await speak(line, voiceId, i);
    writeFileSync(join(AUDIO, `${line.id}.mp3`), mp3);
    writeFileSync(join(OUTDIR, `${line.id}.json`), JSON.stringify(timing, null, 1));
    console.log(`${line.id} — ${timing.duration} s, ${timing.words.length} words`);
  }
  writeIndex();
} else if (cmd === "index") {
  writeIndex();
} else {
  console.log("usage: tts.mjs voices | credits | audition <lineId> <voiceId>… | all <voiceId> [lineId…] | index");
}
