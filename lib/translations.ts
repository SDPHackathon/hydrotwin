export type TranslationKey = keyof typeof translations.en;

export function translate(
  language: Language,
  key: TranslationKey,
  ...args: any[]
): string {
  const dict = translations[language] ?? translations.en;
  const entry = (dict as any)[key] ?? (translations.en as any)[key];

  if (typeof entry === "function") {
    return entry(...args);
  }

  if (typeof entry === "string") {
    return entry;
  }

  return "";
}

/**
 * Translates vulnerable resident profiles into natural Bahasa Melayu for display
 * without mutating underlying resident records or models.
 */
export function translateResidentNeeds(
  needs: string | null | undefined,
  language: Language,
): string {
  if (!needs) return "";
  if (language !== "bm") return needs;

  let text = needs;
  text = text.replace(/Elderly couple/gi, "Pasangan warga emas");
  text = text.replace(/Elderly/gi, "Warga emas");
  text = text.replace(/\((\d+)\s*yo\)/gi, "($1 tahun)");
  text = text.replace(/\b(\d+)\s*yo\b/gi, "$1 tahun");
  text = text.replace(/lives alone/gi, "tinggal bersendirian");
  text = text.replace(/limited mobility/gi, "pergerakan terhad");
  text = text.replace(/Bedridden/gi, "Terlantar sakit");
  text = text.replace(/requires oxygen concentrator/gi, "memerlukan penumpu oksigen");
  text = text.replace(/Ground floor terrace/gi, "Teres tingkat bawah");
  text = text.replace(/family with 2 toddlers/gi, "keluarga bersama 2 kanak-kanak kecil");
  text = text.replace(/Wheelchair user/gi, "Pengguna kerusi roda");
  text = text.replace(/ramp entrance needed/gi, "memerlukan laluan tanjakan");
  text = text.replace(/hearing impaired/gi, "kurang pendengaran");
  text = text.replace(/Two vehicles parked on porch/gi, "Dua kenderaan di anjung");
  text = text.replace(/needs early warning/gi, "memerlukan amaran awal");
  text = text.replace(/Single tenant/gi, "Penyewa bujang");
  text = text.replace(/remote worker/gi, "pekerja jarak jauh");
  text = text.replace(/Dialysis patient/gi, "Pesakit dialisis");
  text = text.replace(/scheduled transport needed/gi, "memerlukan pengangkutan berjadual");
  text = text.replace(/High ground safe zone/gi, "Zon selamat tanah tinggi");
  text = text.replace(/certified first responder/gi, "responder kecemasan bertauliah");

  return text;
}

/**
 * Translates help request types for resident selection and guard task details.
 */
export function translateHelpType(
  type: HelpType | null | undefined,
  language: Language,
): string {
  if (!type) return translate(language, "helpNeeded");
  const key = `helpType_${type}` as TranslationKey;
  return translate(language, key) || translate(language, "helpNeeded");
}

